function calculator() {
let a = 10;
let b = 2;
console.log(a + b); // Addition, Output: 12
console.log(a - b); // Subtraction, Output: 8
console.log(a * b); // Multiplication, Output: 20
console.log(a / b); // Division, Output: 5
console.log(a % b); // Modulus, Output: 0 (remainder of a divided by b)
console.log(a ** b); // Exponentiation, Output: 1000000 (a raised to the power of b)
}   
calculator(); // This will call the calculator function and execute the code inside it, logging the results of the arithmetic operations to the console
