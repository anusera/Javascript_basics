//Function is a nonprimitive data type.
//functions are a block of reusable code that performs a specific task. They can take input parameters and return a value. 

function addition() {
   let a = 5;
   let b = 10;
    console.log(a + b); // This will log the sum of a and b, which is 15
}

//the above block is function definition 
//to execute the function, we need to call it by its name followed by parentheses
addition(); // This will call the addition function and execute the code inside it, logging 15 to the console

